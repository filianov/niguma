/**
 * /api/geo — из какой страны пришёл посетитель.
 *
 * Нужно ради части 6 статьи 27 Закона Украины «Про забезпечення функціонування
 * української мови як державної»: посетителю с территории Украины сайт обязан
 * открываться на украинском языке. Статическая страница страну знать не может —
 * её знает только edge Vercel, который подставляет заголовок x-vercel-ip-country.
 *
 * Отдаём ровно код страны и ничего больше: IP не возвращаем, не пишем в базу и
 * не логируем — определение языка не повод собирать данные о людях.
 *
 * Ответ кэшируется у посетителя на сутки: страна за одну сессию не меняется,
 * а лишний запрос на каждой странице замедлял бы первую отрисовку.
 */
export default function handler(req, res) {
  const country = String(
    req.headers["x-vercel-ip-country"] || req.headers["cf-ipcountry"] || ""
  ).toUpperCase().slice(0, 2);

  res.setHeader("Cache-Control", "private, max-age=86400");
  return res.status(200).json({ ok: true, country: country || null });
}
